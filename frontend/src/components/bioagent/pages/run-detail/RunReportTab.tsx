"use client";

/**
 * Report viewer: publication-friendly presentation of the run with clear
 * separation between observed computational output, technical verification,
 * interpretation boundaries, and reproducibility information.
 */

import * as React from "react";
import { Button } from "@/components/ui/button";
import { FileJson, ImageDown, FileText } from "lucide-react";
import { EmptyState, InfoRow, MonoId, SectionHeading, DemoTag } from "@/components/bioagent/common/primitives";
import { CheckStatusBadge, EvidenceStateBadge, evidenceStateMeta, PolicyBadge, RunStatusBadge } from "@/components/bioagent/common/StatusBadge";
import type { EvidenceState, RunRecord } from "@/lib/bioagent/types";
import { formatTimestamp } from "@/lib/bioagent/format";
import { downloadJson } from "@/lib/bioagent/exports";
import { workflowSpec } from "@/lib/bioagent/workflows";
import { SpatialScatterPlot } from "@/components/bioagent/viz/SpatialScatterPlot";
import { DistributionHistogram } from "@/components/bioagent/viz/legends";
import { categoricalColor, rampColor, ZERO_COLOR } from "@/lib/bioagent/colors";
import { useToast } from "@/hooks/use-toast";
import { downloadSvgAsPng } from "@/lib/bioagent/exports";

const EVIDENCE_STATES: EvidenceState[] = [
  "supported",
  "plausible",
  "hypothesis",
  "unsupported",
  "indeterminate",
];

export function RunReportTab({ run }: { run: RunRecord }) {
  const { toast } = useToast();
  if (!run.report) {
    return (
      <EmptyState
        icon={<FileText className="size-7" />}
        title="Report not generated"
        description="A report is generated only for runs that completed technical verification. This run did not produce one, and that is stated rather than substituted."
      />
    );
  }

  const spec = workflowSpec(run.workflow);
  const exportJson = () => {
    downloadJson(`${run.id}-report.json`, {
      run_id: run.id,
      question: run.question,
      dataset: run.datasetId,
      workflow: run.workflow,
      params: run.params,
      verification: run.verification,
      claims: run.report?.claims,
      figures: run.report?.figures,
      warnings: run.report?.warnings,
      limitations: run.report?.limitations,
      note: "Demo Mode report — illustrative data generated locally.",
    });
    toast({ title: "Report exported", description: `${run.id}-report.json downloaded.` });
  };

  return (
    <article className="space-y-6">
      {/* Report header */}
      <header className="rounded-lg border border-border bg-card p-6">
        <div className="flex flex-wrap items-start justify-between gap-3">
          <div>
            <p className="text-[11px] font-medium uppercase tracking-[0.18em] text-muted-foreground">
              Analysis report · v{run.report.version}
            </p>
            <h2 className="mt-1.5 max-w-2xl text-lg font-semibold leading-snug tracking-tight">
              {run.question}
            </h2>
            <p className="mt-1.5 flex flex-wrap items-center gap-2 text-xs text-muted-foreground">
              <MonoId value={run.id} copy={false} />
              <span>·</span>
              <span>{formatTimestamp(run.report.generatedAt)}</span>
              <span>·</span>
              <RunStatusBadge status={run.status} />
              <DemoTag compact />
            </p>
          </div>
          <div className="flex flex-wrap gap-2">
            <Button size="sm" variant="outline" onClick={exportJson}>
              <FileJson className="size-3.5" aria-hidden />
              Export JSON
            </Button>
          </div>
        </div>
        <p className="mt-4 border-t border-border pt-4 text-sm text-muted-foreground">
          {spec?.title ?? "Unsupported request"} on {run.datasetName}. Generated by a simulated
          workflow execution in Demo Mode — the content below is illustrative and must not be cited
          as an experimental result.
        </p>
      </header>

      {/* 1-2. Dataset and workflow */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-dataset">
        <h3 id="r-dataset" className="text-sm font-semibold">
          Dataset and workflow
        </h3>
        <dl className="mt-3 divide-y divide-border border-t border-border">
          <InfoRow label="Dataset" value={run.datasetName} />
          <InfoRow label="Dataset ID" value={<MonoId value={run.datasetId} copy={false} />} mono />
          <InfoRow label="Workflow" value={spec ? `${spec.title} (registered v1)` : "Unsupported / ambiguous"} />
          <InfoRow label="Configuration" value={<span className="font-mono text-xs">{JSON.stringify(run.params)}</span>} mono />
          <InfoRow label="Policy" value={run.policy ? <PolicyBadge decision={run.policy.decision} /> : "Not reached"} />
        </dl>
      </section>

      {/* 3. Results and visualizations */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-results">
        <h3 id="r-results" className="text-sm font-semibold">
          Results and visualizations
        </h3>
        <ReportFigures run={run} />
      </section>

      {/* 4. Claim classification */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-claims">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <h3 id="r-claims" className="text-sm font-semibold">
            Claim classification
          </h3>
          <p className="text-[10px] font-medium uppercase tracking-widest text-muted-foreground/70">
            five evidence states
          </p>
        </div>
        <p className="mt-1 max-w-3xl text-xs leading-relaxed text-muted-foreground">
          Every statement this report could support is classified into one of five evidence states,
          with the basis and run-local references for each. Classification is a property of the
          linked evidence — not of the sentence&apos;s confidence or tone.
        </p>
        {(run.report.claims ?? []).length > 0 ? (
          <ul className="mt-4 divide-y divide-border rounded-md border border-border">
            {(run.report.claims ?? []).map((claim) => (
            <li key={claim.id} className="px-3 py-3">
              <div className="flex flex-wrap items-start justify-between gap-2">
                <p className="min-w-0 flex-1 text-sm leading-relaxed text-foreground/90">
                  <span className="mr-1.5 font-mono text-[10px] text-muted-foreground">{claim.id}</span>
                  {claim.statement}
                </p>
                <EvidenceStateBadge state={claim.state} />
              </div>
              <p className="mt-1.5 text-xs leading-relaxed text-muted-foreground">
                <span className="font-medium text-foreground/70">Basis: </span>
                {claim.basis}
              </p>
              {claim.references.length > 0 && (
                <p className="mt-1.5 flex flex-wrap items-center gap-1.5">
                  <span className="text-[10px] font-medium uppercase tracking-widest text-muted-foreground/70">
                    traces to
                  </span>
                  {claim.references.map((ref) => (
                    <span
                      key={ref}
                      className="rounded border border-border bg-secondary px-1.5 py-0.5 font-mono text-[10px] text-muted-foreground"
                    >
                      {ref}
                    </span>
                  ))}
                </p>
              )}
            </li>
            ))}
          </ul>
        ) : (
          <p className="mt-3 rounded-md border border-dashed border-border bg-secondary/40 p-4 text-xs text-muted-foreground">
            This report predates claim classification (an older demo record). Re-run the analysis to
            generate a report with classified claims.
          </p>
        )}
        <div className="mt-3 grid gap-2 rounded-md border border-border bg-secondary/40 p-3 sm:grid-cols-2 lg:grid-cols-3">
          {EVIDENCE_STATES.map((state) => (
            <p key={state} className="flex items-start gap-1.5 text-[11px] leading-snug text-muted-foreground">
              <EvidenceStateBadge state={state} className="shrink-0" />
              <span>{evidenceStateMeta[state].hint}</span>
            </p>
          ))}
        </div>
        <p className="mt-3 text-[11px] leading-relaxed text-muted-foreground">
          In this demo the classifications are produced by the demo adapter&apos;s deterministic rules
          over this run&apos;s verification results. In the full system, claims are classified against
          the workflow&apos;s evidence contract before a report is emitted.
        </p>
      </section>

      {/* 5. Technical verification */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-verification">
        <h3 id="r-verification" className="text-sm font-semibold">
          Technical verification
        </h3>
        {run.verification && run.verification.length > 0 ? (
          <ul className="mt-3 divide-y divide-border rounded-md border border-border">
            {run.verification.map((c) => (
              <li key={c.id} className="flex items-start justify-between gap-4 px-3 py-2">
                <div className="min-w-0">
                  <p className="text-xs font-medium">{c.check}</p>
                  <p className="mt-0.5 text-[11px] text-muted-foreground">{c.explanation}</p>
                </div>
                <CheckStatusBadge status={c.status} />
              </li>
            ))}
          </ul>
        ) : (
          <p className="mt-2 text-sm text-muted-foreground">
            Verification checks were not run for this report (see the run timeline).
          </p>
        )}
        <p className="mt-3 text-xs leading-relaxed text-muted-foreground">
          Verification confirms computational artifacts and execution requirements. It does not
          establish biological validity.
        </p>
      </section>

      {/* 5. Warnings */}
      {run.report.warnings.length > 0 && (
        <section className="rounded-lg border border-warning/30 bg-warning/5 p-6" aria-labelledby="r-warnings">
          <h3 id="r-warnings" className="text-sm font-semibold text-warning">
            Warnings
          </h3>
          <ul className="mt-2 list-inside list-disc space-y-1 text-sm text-foreground/90">
            {run.report.warnings.map((w, i) => (
              <li key={i}>{w}</li>
            ))}
          </ul>
        </section>
      )}

      {/* 6. Interpretation boundaries */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-limits">
        <h3 id="r-limits" className="text-sm font-semibold">
          Interpretation boundaries
        </h3>
        <ul className="mt-2 space-y-2 text-sm leading-relaxed text-muted-foreground">
          {run.report.limitations.map((l, i) => (
            <li key={i} className="flex gap-2.5">
              <span className="mt-1.5 size-1.5 shrink-0 rounded-full bg-warning" aria-hidden />
              <span>{l}</span>
            </li>
          ))}
        </ul>
      </section>

      {/* 7. Reproducibility */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-repro">
        <h3 id="r-repro" className="text-sm font-semibold">
          Reproducibility information
        </h3>
        <dl className="mt-3 divide-y divide-border border-t border-border">
          <InfoRow label="Random seed" value={<span className="font-mono text-xs">{JSON.stringify((run.params as { seed?: number }).seed ?? "—")}</span>} mono />
          <InfoRow label="Dataset fingerprint" value={<MonoId value={run.provenance?.fields.find((f) => f.field === "Dataset fingerprint")?.value ?? "Not recorded"} />} />
          <InfoRow
            label="Software versions"
            value="Frontend demo adapter 0.1.0 · Scanpy/Squidpy versions unavailable (backend not connected)"
          />
          <InfoRow label="Artifacts" value={`${run.artifacts.length} files with checksums (see Provenance)`} />
        </dl>
        <p className="mt-2 text-[11px] leading-relaxed text-muted-foreground">
          Because this prototype does not run the scientific backend, replaying this configuration
          reproduces the same demo artifacts deterministically, but not a real scientific result.
        </p>
      </section>

      {/* 8. Provenance and artifacts */}
      <section className="rounded-lg border border-border bg-card p-6" aria-labelledby="r-prov">
        <h3 id="r-prov" className="text-sm font-semibold">
          Provenance and artifacts
        </h3>
        <p className="mt-2 text-sm text-muted-foreground">
          The full provenance record — selector, policy decision, configuration, checksums and
          warnings — is available in the Provenance tab of{" "}
          <span className="font-mono text-xs">{run.id}</span> and in the exported manifest.
        </p>
      </section>
    </article>
  );
}

function ReportFigures({ run }: { run: RunRecord }) {
  const { toast } = useToast();
  const results = run.results;
  if (!results) {
    return (
      <div className="mt-3 rounded-md border border-dashed border-border bg-secondary/40 p-4 text-xs text-muted-foreground">
        No figures belong to this report (the run produced no artifacts).
      </div>
    );
  }

  if (results.kind === "quality_assessment") {
    return (
      <div className="mt-4 grid gap-6 sm:grid-cols-2">
        <figure>
          <p className="mb-1 text-xs font-medium">Figure 1 · Total counts distribution</p>
          <DistributionHistogram values={results.total_counts} xLabel="total counts" />
          <figcaption className="mt-1 text-xs leading-relaxed text-muted-foreground">
            {run.report?.figures[0]?.caption}
          </figcaption>
        </figure>
        <figure>
          <p className="mb-1 text-xs font-medium">Figure 2 · Detected genes distribution</p>
          <DistributionHistogram values={results.n_genes_per_obs} xLabel="n_genes" color="#183345" />
          <figcaption className="mt-1 text-xs leading-relaxed text-muted-foreground">
            {run.report?.figures[1]?.caption}
          </figcaption>
        </figure>
        <div className="sm:col-span-2 overflow-hidden rounded-md border border-border">
          <table className="ba-table">
            <thead>
              <tr className="hover:bg-transparent">
                <th scope="col">Metric</th>
                <th scope="col">Value</th>
              </tr>
            </thead>
            <tbody>
              {results.metrics.map((m) => (
                <tr key={m.label}>
                  <td className="font-medium">{m.label}</td>
                  <td className={m.value === "Not assessed" ? "text-warning" : ""}>{m.value}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    );
  }

  if (results.kind === "spatial_clustering") {
    return (
      <div className="mt-4 space-y-6">
        <FigureBlock
          caption={run.report?.figures[0]?.caption ?? ""}
          svgId={`report-fig1-${run.id}`}
          exportName={`${run.id}-figure1.png`}
          toast={toast}
        >
          <SpatialScatterPlot
            data={results.spatial}
            colorOf={(i) => categoricalColor(results.labels[i])}
            pointSize={3}
            opacity={0.85}
            height={380}
            svgId={`report-fig1-${run.id}`}
            ariaLabel="Report figure 1: spatial clusters"
          />
        </FigureBlock>
        <FigureBlock
          caption={run.report?.figures[1]?.caption ?? ""}
          svgId={`report-fig2-${run.id}`}
          exportName={`${run.id}-figure2.png`}
          toast={toast}
        >
          <SpatialScatterPlot
            data={results.umap}
            colorOf={(i) => categoricalColor(results.labels[i])}
            pointSize={2.6}
            opacity={0.8}
            aspect="auto"
            height={330}
            svgId={`report-fig2-${run.id}`}
            ariaLabel="Report figure 2: embedding colored by cluster"
          />
        </FigureBlock>
        <div className="overflow-hidden rounded-md border border-border">
          <table className="ba-table">
            <thead>
              <tr className="hover:bg-transparent">
                <th scope="col">Cluster</th>
                <th scope="col" className="text-right">Observations</th>
                <th scope="col" className="text-right">Share</th>
              </tr>
            </thead>
            <tbody>
              {results.clusterSizes.map((c) => (
                <tr key={c.label}>
                  <td>
                    <span className="inline-flex items-center gap-2">
                      <span
                        className="size-2.5 rounded-[2px]"
                        style={{ backgroundColor: categoricalColor(c.label) }}
                        aria-hidden
                      />
                      Cluster {c.label}
                    </span>
                  </td>
                  <td className="text-right font-mono text-xs">{c.count.toLocaleString()}</td>
                  <td className="text-right font-mono text-xs">
                    {((c.count / results.labels.length) * 100).toFixed(1)}%
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    );
  }

  // gene expression
  const max = Math.max(...(results.entries[0]?.values ?? [1]));
  return (
    <div className="mt-4 space-y-6">
      {results.entries
        .filter((e) => e.values)
        .map((e, idx) => (
          <FigureBlock
            key={e.resolved}
            caption={run.report?.figures[idx]?.caption ?? ""}
            svgId={`report-gene-${run.id}-${e.resolved}`}
            exportName={`${run.id}-${e.resolved}.png`}
            toast={toast}
          >
            <SpatialScatterPlot
              data={results.spatial}
              colorOf={(i) => {
                const v = e.values![i];
                return v === 0 ? ZERO_COLOR : rampColor(v / max);
              }}
              pointSize={3}
              opacity={0.85}
              height={360}
              svgId={`report-gene-${run.id}-${e.resolved}`}
              ariaLabel={`Report figure: spatial expression of ${e.resolved}`}
            />
          </FigureBlock>
        ))}
    </div>
  );
}

function FigureBlock({
  caption,
  children,
  svgId,
  exportName,
  toast,
}: {
  caption: string;
  children: React.ReactNode;
  svgId: string;
  exportName: string;
  toast: ReturnType<typeof useToast>["toast"];
}) {
  return (
    <figure>
      <div className="mb-2 flex items-center justify-between gap-3">
        <Button
          size="sm"
          variant="ghost"
          className="h-7 text-xs text-muted-foreground"
          onClick={async () => {
            const el = document.getElementById(svgId) as SVGSVGElement | null;
            if (!el) return;
            try {
              await downloadSvgAsPng(el, exportName);
              toast({ title: "Figure exported", description: `${exportName} downloaded.` });
            } catch {
              toast({ title: "Export failed", description: "Could not rasterize this figure." });
            }
          }}
        >
          <ImageDown className="size-3.5" aria-hidden />
          Export figure
        </Button>
      </div>
      {children}
      <figcaption className="mt-2 text-xs leading-relaxed text-muted-foreground">{caption}</figcaption>
    </figure>
  );
}
